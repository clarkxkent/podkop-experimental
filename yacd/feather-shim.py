#!/usr/bin/env python3
"""feather-shim.py ICONS_DIR NAMES_FILE OUT VERSION: the icons of react-feather the dashboard uses
(the export list of src/components/shared/FeatherIcons.ts) as one small module: the shapes of
each icon as data, one component that draws them. react-feather gives each icon a component
of its own with prop-types; the drawing is the same."""
import json
import re
import sys

icons_dir, names_file, out = sys.argv[1:4]  # and the version of react-feather
names = re.findall(r"\b([A-Z][A-Za-z0-9]*)\b", open(names_file).read().split("{", 1)[1].split("}", 1)[0])


def file_of(name):
    special = {"GitHub": "github"}
    if name in special:
        return special[name]
    return re.sub(r"(?<!^)(?=[A-Z0-9])", "-", name).lower()


shapes = {}
for name in names:
    text = open(f"{icons_dir}/{file_of(name)}.js").read()
    children = []
    for tag, attrs in re.findall(r'React\.createElement\("(\w+)", \{([^}]*)\}\)', text):
        if tag == "svg":
            continue
        children.append([tag, dict(re.findall(r'(\w+): "([^"]*)"', attrs))])
    if not children:
        sys.exit(f"no shapes for {name}")
    shapes[name] = children

lines = [
    "// The icons of react-feather (MIT, Cole Bemis) the dashboard uses, as data: generated by",
    "// tools/feather-shim.py of the podkop-exp build from react-feather " + sys.argv[4] + ".",
    "import { createElement, forwardRef } from 'react';",
    "",
    "type Shape = [string, Record<string, string>];",
    "",
    "function icon(name: string, shapes: Shape[]) {",
    "  const Icon = forwardRef<SVGSVGElement, any>(({ color = 'currentColor', size = 24, ...rest }, ref) =>",
    "    createElement(",
    "      'svg',",
    "      {",
    "        ref,",
    "        xmlns: 'http://www.w3.org/2000/svg',",
    "        width: size,",
    "        height: size,",
    "        viewBox: '0 0 24 24',",
    "        fill: 'none',",
    "        stroke: color,",
    "        strokeWidth: '2',",
    "        strokeLinecap: 'round',",
    "        strokeLinejoin: 'round',",
    "        ...rest,",
    "      },",
    "      ...shapes.map(([tag, attributes], key) => createElement(tag, { key, ...attributes })),",
    "    ),",
    "  );",
    "  Icon.displayName = name;",
    "  return Icon;",
    "}",
    "",
]
for name in names:
    lines.append(f"export const {name} = icon('{name}', {json.dumps(shapes[name], separators=(',', ':'))});")
open(out, "w").write("\n".join(lines) + "\n")
print(len(names), "icons")
